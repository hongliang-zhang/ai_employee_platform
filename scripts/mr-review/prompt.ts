const PYTHON_EXAMPLE = [
  'import json',
  'result = {',
  '  "comments": [',
  '    {"path": "packages/gateway/src/routes.ts", "line": 42, "side": "RIGHT", "body": "评论内容，不含换行符"}',
  '  ],',
  '  "summary": "整体评价，不含换行符"',
  '}',
  "with open('/home/user/review.json', 'w') as f:",
  '    json.dump(result, f, ensure_ascii=False)',
  'print(json.dumps(result, ensure_ascii=False))',
].join('\n')

export function buildPrompt(diff: string): string {
  return [
    '# 任务',
    '你是 z-mono 项目的 code reviewer，请审查以下 MR diff。',
    '',
    '# 核心原则',
    '- **只基于 diff 中实际变更的代码做判断**。不要基于 git 历史、分支上的其他 commit、或 diff 之外的文件做推断。',
    '- **只报告确定存在的问题**。不要做防御性建议（如「建议加类型校验」）、假设性风险提示（如「如果将来调用方变了会出问题」）、或泛化的最佳实践推荐。',
    '- **没有问题就返回空 comments**。如果 diff 没有实际的 bug、安全漏洞或架构违反，comments 应为空数组 `[]`。不要为了"找到点什么"而报出低价值问题。',
    '',
    '# 项目架构约定',
    '- gateway 是唯一可信后端，拥有所有存储和 LLM 访问权限',
    '- sandbox（e2b）是不可信的，只能通过 scoped JWT 访问 gateway',
    '- sandbox 不能直接访问数据库或持有平台 secrets',
    '- 所有错误响应必须符合 { error: { code, message, retryable, details } } 格式',
    '- migrations 只能追加，不能修改已有迁移文件',
    '- dispatcher 管理 sandbox 生命周期，gateway 不感知 sandbox',
    '',
    '# 评审维度',
    '只审查以下维度中的**实际问题**：',
    '- Bug / 逻辑错误（边界条件、异步错误处理、竞态）',
    '- 安全漏洞（JWT 泄露、sandbox 边界违反、secrets 暴露、SQL 注入）',
    '- 架构约定违反（跨边界直接访问、error shape 不符、迁移文件修改）',
    '- 代码质量与可维护性（命名、复杂度、重复代码）',
    '',
    '每条 comment 必须指向 diff 中具体变更的行，并说明**为什么**这是一个实际 bug 或违反，而不是"可能"或"建议"。',
    '',
    '# 输出格式（严格遵守）',
    '',
    '运行以下 Python 脚本将结果写入 /home/user/review.json 并同时输出到 stdout：',
    '',
    PYTHON_EXAMPLE,
    '',
    '严格规则：',
    '- 每个 body 和 summary 必须是单行字符串，不含换行符',
    '- 使用 json.dump 写文件，不要手写 JSON 字符串',
    '- 不要在终端打印任何内容，只写文件',
    '- 写完文件后不要做任何其他操作',
    '',
    '# Diff',
    diff,
  ].join('\n')
}
